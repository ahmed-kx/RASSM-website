import { z } from "zod";
import {
  categorySchema,
  type Category,
  hexColorSchema,
  idSchema,
  imageUrlSchema,
  isoDateSchema,
  priceDaSchema,
  SIZES,
  slugSchema,
  type Size,
} from "./common";
import { deliveryDiscountTiersSchema } from "./delivery-discount";
import { formatPrice } from "../utils/format-price";

/** Units in stock for one size. */
function sizeStockSchema(size: Size) {
  return z
    .number({
      error: (issue) =>
        issue.input === undefined
          ? `Stock manquant pour la taille ${size} : indiquez 0 si elle n'est pas vendue ou épuisée.`
          : `Le stock de la taille ${size} doit être un nombre.`,
    })
    .int(`Le stock de la taille ${size} doit être un nombre entier.`)
    .nonnegative(`Le stock de la taille ${size} ne peut pas être négatif.`);
}

/**
 * Units in stock for every size of one color. All five sizes must be present
 * (0 = not sold or sold out).
 */
export const stockBySizeSchema = z.object(
  Object.fromEntries(SIZES.map((size) => [size, sizeStockSchema(size)])) as Record<
    Size,
    ReturnType<typeof sizeStockSchema>
  >,
  { error: "Indiquez le stock de chaque taille pour cette couleur." },
);
export type StockBySize = z.infer<typeof stockBySizeSchema>;

/** One color of a product. Stock is tracked per variant: this color × each size. */
export const productColorSchema = z.object({
  name: z.string().trim().min(1, "Le nom de la couleur est obligatoire."),
  hex: hexColorSchema,
  /**
   * Photos of this color. When a product has photos per color, the gallery shows the
   * selected color's photos; otherwise it shows the product `images`.
   */
  images: z.array(imageUrlSchema).optional(),
  /** Stock of this color for each size. */
  stock: stockBySizeSchema,
});
export type ProductColor = z.infer<typeof productColorSchema>;

/** SKU letter per category: RSM-H-001 (hoodies), RSM-S-001 (sweatshirts), RSM-T-001 (t-shirts). */
export const SKU_PREFIXES: Record<Category, string> = {
  hoodie: "RSM-H-",
  sweatshirt: "RSM-S-",
  tshirt: "RSM-T-",
};

/** "RSM-H-007": readable, unique, generated by the API (never typed by hand). */
export const skuSchema = z
  .string()
  .regex(/^RSM-[HST]-\d{3,}$/, "La référence doit avoir la forme RSM-H-001.");

export function formatSku(category: Category, number: number): string {
  return `${SKU_PREFIXES[category]}${String(number).padStart(3, "0")}`;
}

export const productSchema = z.object({
  id: idSchema,
  /** Internal reference (dashboard, Anderson export). */
  sku: skuSchema,
  name: z
    .string()
    .trim()
    .min(2, "Le nom du produit est trop court.")
    .max(80, "Le nom du produit ne doit pas dépasser 80 caractères."),
  slug: slugSchema,
  description: z
    .string()
    .trim()
    .min(10, "La description est trop courte.")
    .max(2000, "La description ne doit pas dépasser 2 000 caractères."),
  category: categorySchema,
  /** Price in DA (integer). */
  price: priceDaSchema.positive("Le prix doit être supérieur à 0."),
  images: z.array(imageUrlSchema).min(1, "Un produit doit avoir au moins une image."),
  colors: z
    .array(productColorSchema)
    .min(1, "Un produit doit avoir au moins une couleur.")
    .refine(
      (colors) => new Set(colors.map((color) => color.name)).size === colors.length,
      "Deux couleurs du même produit ne peuvent pas avoir le même nom.",
    ),
  featured: z.boolean(),
  isActive: z.boolean(),
  /**
   * Quantity-based delivery discount tiers (empty = none). They reduce the delivery
   * fee only, never the product price. See `getDeliveryFeeWithDiscount`.
   */
  deliveryDiscountTiers: deliveryDiscountTiersSchema,
  /** Collection drop label, e.g. "Drop 001". */
  drop: z.string().regex(/^Drop \d{3}$/, 'Le drop doit avoir la forme "Drop 001".'),
  createdAt: isoDateSchema,
});
export type Product = z.infer<typeof productSchema>;

/**
 * Product schema that also checks every tier amount is lower than the highest home
 * delivery price. Use it wherever products are created or edited (admin form, API,
 * mocks), passing `getMaxHomeDeliveryPrice(deliveryFees)`. Never hard-code the limit.
 */
export function createProductSchema(maxHomeDeliveryPrice: number) {
  return productSchema.superRefine((product, ctx) =>
    checkTierAmounts(product.deliveryDiscountTiers, maxHomeDeliveryPrice, ctx),
  );
}

/** Adds an error under each tier amount that is not lower than the highest home price. */
export function checkTierAmounts(
  tiers: Product["deliveryDiscountTiers"],
  maxHomeDeliveryPrice: number,
  ctx: z.RefinementCtx,
): void {
  tiers.forEach((tier, index) => {
    if (tier.type === "amount" && tier.amount >= maxHomeDeliveryPrice) {
      ctx.addIssue({
        code: "custom",
        path: ["deliveryDiscountTiers", index, "amount"],
        message: `Le montant de la réduction doit être inférieur au tarif de livraison à domicile le plus élevé (${formatPrice(maxHomeDeliveryPrice)}).`,
      });
    }
  });
}

// Stock helpers: stock lives on each color (variant = color + size).

type StockProduct = Pick<Product, "colors">;

/** Stock of one variant; 0 for an unknown color. */
export function getVariantStock(product: StockProduct, colorName: string, size: Size): number {
  return product.colors.find((color) => color.name === colorName)?.stock[size] ?? 0;
}

/** Stock of a size across all colors. */
export function getSizeStock(product: StockProduct, size: Size): number {
  return product.colors.reduce((sum, color) => sum + color.stock[size], 0);
}

/** True when at least one variant is in stock. */
export function isProductInStock(product: StockProduct): boolean {
  return product.colors.some((color) => SIZES.some((size) => color.stock[size] > 0));
}
